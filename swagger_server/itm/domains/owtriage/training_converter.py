import argparse
import csv
import os
import pprint
import sys
import yaml
from scenario_converter import add_ow_scenes

"""
This utility takes in existing phase 2 training YAMLs and a description map (whose template was generated by
`template_maker.py`) and converts the training YAMLs into their Open World 3 equivalents.

High-level algorithm:
- Process command line arguments
- Generate description map from csv
- Process all Phase 2 YAML files-- the specified number of files for the specified KDMA(s)
  - Parse the input YAML file
  - Convert id and name to OW3 equivalents; add `first_scene`
  - Scan through input YAML patients and save patient data (except for duplicates)
    - Generate descriptions from description map
    - Add vitals from description map
  - Propagate new Patient ID to original YAML scenes for probe mapping
  - Add open world scenes via `scenario_converter.add_ow_scenes`
  - Save new OW3 YAML

Usage: training_converter.py [-h] [-v] [-e evalname] [-c COUNT] [-n] [-o outpath] [-k kdma]
Options:
  -h, --help            show this help message and exit
  -v, --verbose         Verbose logging
  -e evalname, --evalname evalname
                        Short name for evaluation (no spaces); default Feb2026
  -c COUNT, --count COUNT
                        Number of training files per kdma to process
  -n, --no_output       Do not write output files
  -o outpath, --outpath outpath
                        Specify location for output files (no spaces)
  -k kdma, --kdma kdma  Which kdma to process (default is process both AF and MF)
"""

# These are constants that cannot be overridden via the command line
DEFAULT_EVALUATION_NAME = 'Feb2026'
DEFAULT_OUT_PATH = f"swagger_server/itm/data/{DEFAULT_EVALUATION_NAME.lower()}/scenarios"
TA1_NAME = 'adept'
DESCRIPTION_MAP_FILENAME = 'description_map.csv'

# These are default values that can be overridden via the command line
NUM_FILES = 10
REDACT_EVAL = False
VERBOSE = False
EVALUATION_NAME = DEFAULT_EVALUATION_NAME
WRITE_FILES = True
OUT_PATH = DEFAULT_OUT_PATH
KDMAS = ['AF', 'MF']
KDMA_MAP: dict = {'AF': 'Affiliation Focus', 'MF': 'Merit Focus'}


class FoldableDumper(yaml.Dumper):
    def increase_indent(self, flow=False, indentless=False):
        # Overriding indentless=False forces list items to indent
        return super(FoldableDumper, self).increase_indent(flow, False)


def add_characters(scene: dict, description_map: dict, ow_char_info: dict):
    for char_pos in range(2): # There are always two characters, Patient A and Patient B
        candidate_char = scene['state']['characters'][char_pos]
        char_med_desc, char_attr_desc = candidate_char['unstructured'].splitlines()
        if VERBOSE:
            print(f"Got char_med_desc of `{char_med_desc}` and char_attr_desc of `{char_attr_desc}`")
        char_med_info = description_map.get(char_med_desc)
        char_attr_info = description_map.get(char_attr_desc)
        if not (char_med_info and char_attr_info):
            print(f"WARNING: no description map for description `{candidate_char['unstructured']}`.")
            continue
        char_near_treated_desc: str = char_attr_info['near_treated_desc'] + char_med_info['near_treated_desc']
        char_near_desc = char_near_treated_desc.replace(' treated', '', 1)
        char_far_desc: str = char_attr_info['far_treated_desc'] + char_med_info['far_untreated_desc']
        char_far_treated_desc = char_attr_info['far_treated_desc'] + char_med_info['far_treated_desc']
        new_patient_num = None
        for ow_char in ow_char_info.values():
            if ow_char['unstructured_near'] == char_near_desc:
                if VERBOSE:
                    print(f"--> Already added '{char_near_desc}'.")
                new_patient_num = ow_char['id']
                break

        if new_patient_num:
            char_id = f"Patient {new_patient_num}"
            pass # Already added character with this permutation of med/attr text
        else:
            # Create the new character
            new_patient_num = len(ow_char_info) + 1
            char_id = f"Patient {new_patient_num}"
            vitals = {'heart_rate': char_med_info['pulse'].upper(),
                    'breathing': char_med_info['resp'].upper(),
                    'avpu': char_med_info['avpu'].upper()
                    }
            character: dict = {'id': char_id, 'name': char_id, 'unstructured': char_near_desc, 'unstructured_near': char_near_desc,
                            'unstructured_treated_near': char_near_treated_desc,
                            'unstructured_far': char_far_desc,
                            'unstructured_treated_far': char_far_treated_desc,
                            'medical_condition': candidate_char['medical_condition'],
                            'attribute_rating': candidate_char['attribute_rating'],
                            'vitals': vitals,
                            'nearby': bool(new_patient_num % 2), # Every other patient is nearby
                            'distance': 0 if new_patient_num % 2 else 21, # distant patients are 21 feet away
                            'treated': False,
                            'unseen': False
                            }
            ow_char_info[char_id] = character

        # Original YAML needs the Patient ID so server can build the probe mappings
        candidate_char['id'] = char_id
        mapping = scene['action_mapping'][char_pos]
        mapping['character_id'] = char_id
        mapping['unstructured'] = "Treat " + char_id
        mapping['action_id'] = '_'.join(['treat', 'patient', str(new_patient_num)]) # e.g., treat_patient_7


def process_yaml_file(kdma, file_num, description_map):
    # Construct input and output file paths
    input_filename = f"{EVALUATION_NAME.lower()}-{TA1_NAME}-train-{kdma}{file_num}.yaml"
    output_filename = f"{EVALUATION_NAME.lower()}-{TA1_NAME}-train-openworld3-{kdma}{file_num}.yaml"
    input_filespec = os.path.join(DEFAULT_OUT_PATH, input_filename)
    output_filespec = os.path.join(OUT_PATH, output_filename)

    try:
        print(f"Processing yaml file {input_filename}.")
        # Read and parse the YAML file
        with open(input_filespec, 'r', encoding='utf-8') as infile:
            yaml_data = yaml.safe_load(infile)

        # Convert id and name
        old_id = yaml_data['id']
        index = old_id.index(kdma)
        yaml_data['id'] = f"{old_id[:index]}{'OW3_'}{old_id[index:]}" # Convert Feb2026-AF0-train to Feb2026-OW3_AF0-train
        # Convert "Affiliation Focus Training Set 0" to "Affiliation Focus Open World 3 Training Set 0"
        yaml_data['name'] = f"{KDMA_MAP[kdma]} Open World Part 3 Training Set {file_num}"

        # Insert first scene in its typical location
        items = list(yaml_data.items())
        items.insert(2, ('first_scene', 'treat_and_tag'))
        yaml_data = dict(items)

        ow_char_info: dict = {}
        for scene in yaml_data['scenes']:
            add_characters(scene, description_map, ow_char_info)
        if VERBOSE:
            print("\nOW Char info:")
            pprint.pprint(ow_char_info, indent=2)

        add_ow_scenes(yaml_data, ow_char_info)

        # If requested, write the OW3-style YAML file
        if WRITE_FILES:
            with open(output_filespec, 'w', encoding='utf-8') as outfile:
                yaml.dump(yaml_data, outfile, Dumper=FoldableDumper, sort_keys=False, indent=2)

        print(f"--> Successfully processed and {'wrote' if WRITE_FILES else 'did NOT write'}: {output_filespec}")

    except yaml.YAMLError as exc:
        print(f"Error parsing YAML in file '{input_filename}': {exc}", file=sys.stderr)
    except IOError as exc:
        print(f"I/O Error processing file '{input_filename}': {exc}", file=sys.stderr)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description='Converts TA1 training YAMLs into their Open World 3 equivalents.')
    parser.add_argument('-v', '--verbose', action='store_true', required=False, default=False,
                        help='Verbose logging')
    parser.add_argument('-e', '--evalname', required=False, metavar='evalname', default=DEFAULT_EVALUATION_NAME,
                        help=f'Short name for evaluation (no spaces); default {DEFAULT_EVALUATION_NAME}')
    parser.add_argument('-c', '--count', type=int, required=False, default=NUM_FILES,
                        help='Number of training files per kdma to process')
    parser.add_argument('-n', '--no_output', action='store_true', required=False, default=False,
                        help='Do not write output files')
    parser.add_argument('-o', '--outpath', required=False, metavar='outpath',
                        help='Specify location for output files (no spaces)')
    parser.add_argument('-k', '--kdma', metavar='kdma', required=False, type=str,
                        help="Which kdma to process (default is process both AF and MF)")

    args = parser.parse_args()
    if args.verbose:
        VERBOSE = True
    if args.evalname:
        EVALUATION_NAME = args.evalname
        OUT_PATH = OUT_PATH.replace(DEFAULT_EVALUATION_NAME.lower(), EVALUATION_NAME.lower())
    if args.count is not None:
        if args.count > 1:
            NUM_FILES = args.count
        else:
            print(f"Unsupported number of training files to process ({args.count}) provided; must be at least 1.")
            exit(1)
    if args.no_output:
        WRITE_FILES = False
    if args.outpath:
        OUT_PATH = args.outpath
    if args.kdma:
        if args.kdma.upper() not in KDMAS:
            print(f"Unsupported kdma `{args.kdma}` with -k flag.")
            exit(1)
        KDMAS = [args.kdma.upper()]

    # Read the description map csv
    description_map: dict = {}
    with open(DESCRIPTION_MAP_FILENAME, mode='r', newline='', encoding='utf-8-sig') as file:
        reader = csv.DictReader(file)
        # Use the 'ta1_description' column as the main key
        description_map = {row['ta1_description']: row for row in reader}

    if VERBOSE:
        print(description_map.keys())

    # Ensure the output directory exists
    os.makedirs(OUT_PATH, exist_ok=True)

    # Process all Phase 2 YAML files
    for kdma in KDMAS:
        for file_num in range(0, NUM_FILES):
            process_yaml_file(kdma, file_num, description_map)

    print('Done.')
