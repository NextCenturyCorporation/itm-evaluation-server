VICTIM_MAPPINGS: list = [
    {('shot', 'shoot'): "are a victim in the shooting."},
    {('IED', 'bomb', 'weapon'): "are a bystander who was injured."},
    {('crash', 'car accident', 'driver'): "were injured in the crash."},
    {('abandoned', 'attack'): "were injured in the attack."},
    {('collapsing', 'wall'): "were injured by the wall."},
    {('fight', 'brawl'): "were injured in the fight."}
]

# These are default values that can be overridden via the command line
NUM_FILES = 10
NUM_PROBES = 8
REDACT_EVAL = False
VERBOSE = False
EVALUATION_NAME = DEFAULT_EVALUATION_NAME
WRITE_FILES = True
OUT_PATH = DEFAULT_OUT_PATH
KDMAS = ['AF', 'MF']
KDMA_MAP: dict = {'AF': 'Affiliation Focus', 'MF': 'Merit Focus'}


class FoldableDumper(yaml.Dumper):
    def increase_indent(self, flow=False, indentless=False):
        # Overriding indentless=False forces list items to indent
        return super(FoldableDumper, self).increase_indent(flow, False)


# Finds and returns an existing patient with the specified medical and attribute info, or returns None if not found
def find_patient(all_patients: dict, med_info: dict, attr_info: dict) -> dict:
    char_near_treated_desc: str = attr_info['near_treated_desc'] + med_info['near_treated_desc']
    for patient in all_patients.values():
        if patient['unstructured_treated_near'] == char_near_treated_desc:
            if VERBOSE:
                print(f"--> Found previous patient {patient['id']} with near/treated desc `{char_near_treated_desc}`.")
            return patient
    return None


# Finds the "victim" (merit=1.0) of the specified character
def get_mf_victim(perp_desc: str) -> dict:
    # NOTE: this code only works if there are at least two keywords per mapping.
    for mapping in VICTIM_MAPPINGS:
        for keywords, victim_desc in mapping.items():
            if any(term in perp_desc for term in keywords):
                return victim_desc

    print(f"Warning: could not find victim description for `{perp_desc}`. Exiting.")
    exit(1)


# Determines if two characters are a valid pairing in a probe; returns False if either is empty
def valid_pair(char1, char2) -> bool:
    if not char1 or not char2:
        return False

    # Patients cannot have a zero attribute delta
    return char1['attribute_rating'] == char2['attribute_rating']


# Create a character with the specified patient number given the specified medical and attribute info
# Return the character
def make_character(med_info: dict, attr_info: dict, new_patient_num) -> dict:
    char_near_treated_desc: str = attr_info['near_treated_desc'] + med_info['near_treated_desc']
    char_near_desc: str = char_near_treated_desc.replace(' treated', '', 1)
    char_far_desc: str = attr_info['far_treated_desc'] + med_info['far_untreated_desc']
    char_far_treated_desc: str = attr_info['far_treated_desc'] + med_info['far_treated_desc']

    # Create the new character
    char_id = f"Patient {new_patient_num}"
    vitals = {'heart_rate': med_info['pulse'].upper(),
            'breathing': med_info['resp'].upper(),
            'avpu': med_info['avpu'].upper()
            }
    character: dict = {'id': char_id, 'name': char_id, 'unstructured': char_near_desc, 'unstructured_near': char_near_desc,
                    'unstructured_treated_near': char_near_treated_desc,
                    'unstructured_far': char_far_desc,
                    'unstructured_treated_far': char_far_treated_desc,
                    'medical_condition': float(med_info['value']),
                    'attribute_rating': float(attr_info['value']),
                    'vitals': vitals,
                    'nearby': bool(new_patient_num % 2), # Every other patient is nearby
                    'distance': 0 if new_patient_num % 2 else 21, # distant patients are 21 feet away
                    'treated': False,
                    'unseen': False
                    }
    return character


# Returns an action mapping with the specified character, probe, and scene info
def make_mapping(ch_info: dict, kdma: str, scene_num: int, choice: str) -> dict:
    character_num = ch_info['id'].split()[-1]
    return {
        'action_id': f"treat_patient_{character_num}",
        'action_type': 'TREAT_PATIENT',
        'unstructured': f"Treat Patient {character_num}",
        'character_id': ch_info['id'],
        'probe_id': f"Probe {kdma}{scene_num}",
        'choice': f"Response {kdma}{scene_num}-{choice}",
        'kdma_association': {
            'medical': ch_info['medical_condition'],
            'merit' if kdma == 'MF' else 'affiliation': ch_info['attribute_rating']
        }
    }


# Create and return a probe scene where the choice is to treat one of the two specified characters (patients)
# Note that this scene will never be seen nor exercised by the ADM; it is merely there to contain probe details
def make_scene(ch1_info: dict, ch2_info: dict, kdma: str, scene_num) -> dict:
    first_char = random.choice([ch1_info, ch2_info])
    second_char = ch2_info if first_char['id'] == ch1_info['id'] else ch1_info
    characters: list = [
        {
        'id': first_char['id'],
        'name': first_char['name'],
        'unstructured': first_char['unstructured'],
        'medical_condition': first_char['medical_condition'],
        'attribute_rating': first_char['attribute_rating']
        },
        {
        'id': second_char['id'],
        'name': second_char['name'],
        'unstructured': second_char['unstructured'],
        'medical_condition': second_char['medical_condition'],
        'attribute_rating': second_char['attribute_rating']
        }
    ]
    action_mapping: list = [
        make_mapping(first_char, kdma, scene_num, 'A'),
        make_mapping(second_char, kdma, scene_num, 'B')
    ]
    return {
        'id': f"Scene {scene_num}",
        'end_scene_allowed': False,
        'state': {
            'unstructured': "Unused",
            'characters': characters
        },
        'action_mapping': action_mapping
    }


# Create and return a "probe scene" to the scenario involving two random characters
def create_scene(scene_num: int, kdma: str, ow_char_info: dict, med_map: dict, attr_map: dict) -> dict:
    # Generate a random Patient A (can already be in the scenario)
    med_keys: list = list(med_map.keys())
    attr_keys: list = list(attr_map.keys())
    char_med_desc: str = random.choice(med_keys)
    char_attr_desc: str = random.choice(attr_keys)
    if kdma == 'MF':
        while float(attr_map[char_attr_desc]['value']) == float(1):  # First char can't be the victim
            char_attr_desc = random.choice(attr_keys)

    if not (ch1_info := find_patient(ow_char_info, med_map[char_med_desc], attr_map[char_attr_desc])):
        ch1_info = make_character(med_map[char_med_desc], attr_map[char_attr_desc], len(ow_char_info) + 1)
        ow_char_info[ch1_info['id']] = ch1_info

    # Create a random second character who:
    #   if an MF probe, is the victim of the first patient
    #   if an AF probe, has a non-zero attribute delta from the first patient
    ch2_info = None
    while not ch2_info:
        char_med_desc = random.choice(med_keys)
        if kdma == 'MF':
            char_attr_desc = get_mf_victim(char_attr_desc) # Look up victim of first patient based on scene
        else:
            char_attr_desc = random.choice(attr_keys)
        if VERBOSE:
            print(f"Trying `{char_med_desc}` and `{char_attr_desc}`")
        ch2_info = find_patient(ow_char_info, med_map[char_med_desc], attr_map[char_attr_desc])
        if not ch2_info:
            ch2_info = make_character(med_map[char_med_desc], attr_map[char_attr_desc], len(ow_char_info) + 1)
        if kdma != 'MF' and valid_pair(ch1_info, ch2_info):
            ch2_info = None # First and second patient must be a valid pairing

    if ch1_info['attribute_rating'] == ch2_info['attribute_rating']:
        print("ERROR: Patients cannot have same attribute rating!")
        exit(1)

    ow_char_info[ch2_info['id']] = ch2_info

    # Return a probe scene where the choice is to treat one of these two patients
    return make_scene(ch1_info, ch2_info, kdma, scene_num)


def generate_yaml_files(kdmas, file_num, medical_map, merit_map, affiliation_map):
    # Construct output file paths
    output_filename = f"{EVALUATION_NAME.lower()}-{TA1_NAME}-train-openworld3-synth{file_num}.yaml"
    output_filespec = os.path.join(OUT_PATH, output_filename)

    try:
        yaml_data: dict = {}

        # Create top-level metadata
        yaml_data['id'] = f"{EVALUATION_NAME}-{'OW3_'}train_{file_num}" # e.g., Feb2026-OW3_train_8
        yaml_data['name'] = f"Open World Part 3 Synthetic Training Set {file_num}"
        yaml_data['first_scene'] = 'treat_and_tag'
        scenes: list = []
        ow_char_info: dict = {}

        while len(scenes) < NUM_PROBES:
            kdma = kdmas[len(scenes) % len(kdmas)] # Alternate between AF and MF probes if necessary
            scenes.append(create_scene(len(scenes) + 1, kdma, ow_char_info, medical_map.copy(),
                                       merit_map.copy() if kdma == 'MF' else affiliation_map.copy()))
            if VERBOSE:
                print(f'Added {kdma} scene #{len(scenes)}:')

        # Add scenario-level state and all "probe scenes" (that TA2 never sees)
        yaml_data['state'] = {
            'unstructured': BACKGROUND_INFO,
            'characters': scenes[0]['state']['characters']
        }
        yaml_data['scenes'] = scenes

        add_ow_scenes(yaml_data, ow_char_info)

        # If requested, write the OW3-style YAML file
        if WRITE_FILES:
            with open(output_filespec, 'w', encoding='utf-8') as outfile:
                yaml.dump(yaml_data, outfile, Dumper=FoldableDumper, sort_keys=False, indent=2)

        print(f"--> Successfully processed and {'wrote' if WRITE_FILES else 'did NOT write'}: {output_filespec}")

    except IOError as exc:
        print(f"I/O Error processing file '{output_filespec}': {exc}", file=sys.stderr)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description='Generates Open World 3 scenario YAMLs based on randomized TA1 patient combinations.')
    parser.add_argument('-v', '--verbose', action='store_true', required=False, default=False,
                        help='Verbose logging')
    parser.add_argument('-e', '--evalname', required=False, metavar='evalname', default=DEFAULT_EVALUATION_NAME,
                        help=f'Short name for evaluation (no spaces); default {DEFAULT_EVALUATION_NAME}')
    parser.add_argument('-c', '--count', type=int, required=False, default=NUM_FILES,
                        help='Number of training files to generate')
    parser.add_argument('-p', '--probes', type=int, required=False, default=NUM_PROBES,
                        help=f"Number of probes to generate per file (default {NUM_PROBES})")
    parser.add_argument('-n', '--no_output', action='store_true', required=False, default=False,
                        help='Do not write output files')
    parser.add_argument('-o', '--outpath', required=False, metavar='outpath',
                        help='Specify location for output files (no spaces)')
    parser.add_argument('-k', '--kdma', metavar='kdma', required=False, type=str,
                        help="Which kdma(s) to include in resulting YAML files (default is AF+MF)")

    args = parser.parse_args()
    if args.verbose:
        VERBOSE = True
    if args.evalname:
        EVALUATION_NAME = args.evalname
        OUT_PATH = OUT_PATH.replace(DEFAULT_EVALUATION_NAME.lower(), EVALUATION_NAME.lower())
    if args.probes is not None:
        if args.probes > 2 and args.probes < 20:
            NUM_PROBES = args.probes
        else:
            print(f"Unsupported number of probes to generate ({args.probes}) provided; must be between 2 and 20.")
            exit(1)
    if args.count is not None:
        if args.count > 1:
            NUM_FILES = args.count
        else:
            print(f"Unsupported number of training files to process ({args.count}) provided; must be at least 1.")
            exit(1)
    if args.no_output:
        WRITE_FILES = False
    if args.outpath:
        OUT_PATH = args.outpath
    if args.kdma:
        if args.kdma.upper() not in KDMAS:
            print(f"Unsupported kdma `{args.kdma}` with -k flag.")
            exit(1)
        KDMAS = [args.kdma.upper()]

    # Read the description map csv
    medical_map: dict = {}
    affiliation_map: dict = {}
    merit_map: dict = {}
    with open(DESCRIPTION_MAP_FILENAME, mode='r', newline='', encoding='utf-8-sig') as file:
        rows = list(csv.DictReader(file))
        # Use the 'ta1_description' column as the main key
        medical_map = {row['ta1_description']: row for row in rows if row['kdma'] == 'MED'}
        merit_map = {row['ta1_description']: row for row in rows if row['kdma'] == 'MF'}
        affiliation_map = {row['ta1_description']: row for row in rows if row['kdma'] == 'AF'}

    if VERBOSE:
        print(medical_map.keys())
        print(affiliation_map.keys())
        print(merit_map.keys())

    # Ensure the output directory exists
    os.makedirs(OUT_PATH, exist_ok=True)

    # Generate all OW3 YAML training files
    for file_num in range(0, NUM_FILES):
        generate_yaml_files(KDMAS, file_num, medical_map, merit_map, affiliation_map)

    print('Done.')
